// ─────────────────────────────────────────────────────────────────────
// Area card — collapsible, with topic table + "Your input" line
// ─────────────────────────────────────────────────────────────────────

function AreaCard({
  area,
  isOpen,
  onToggle,
}: {
  area: DiscussionArea;
  isOpen: boolean;
  onToggle: () => void;
}): JSX.Element {
  const panelId = `r7-area-${area.id}`;
  const printMode = usePrintMode();
  return (
    <article
      className="overflow-hidden"
      style={{
        background: 'rgb(var(--white))',
        border: '1px solid rgb(var(--border))',
        borderTop: `3px solid ${DILIGENCE}`,
      }}
    >
      {/* Disclosure header */}
      <button
        type="button"
        onClick={onToggle}
        aria-expanded={isOpen}
        aria-controls={panelId}
        className="flex w-full items-start justify-between gap-3 text-left"
        style={{ padding: '14px 16px', background: 'transparent' }}
      >
        <div className="min-w-0 flex-1">
          <div className="mb-1 flex items-baseline gap-2">
            <span
              className="font-mono text-[11px] font-bold"
              style={{ color: 'rgb(var(--diligence-text))' }}
            >
              {area.number}.
            </span>
            <span
              className="font-mono text-overline font-bold uppercase"
              style={{
                color: 'rgb(var(--diligence-text))',
                letterSpacing: '0.12em',
              }}
            >
              {area.overline}
            </span>
          </div>
          <p
            className="m-0 font-sans text-h4 font-semibold text-ink"
            style={{ fontSize: 14, lineHeight: 1.35 }}
          >
            {area.question}
          </p>
        </div>
        {/* Omitted on the print route, where the header reads as a heading. */}
        {!printMode && (
          <span
            aria-hidden="true"
            className="flex h-7 w-7 flex-shrink-0 items-center justify-center"
            style={{
              color: 'rgb(var(--diligence-text))',
              background: 'rgb(var(--surface))',
              transform: isOpen ? 'rotate(0deg)' : 'rotate(-90deg)',
              transition: 'transform 180ms ease',
            }}
          >
            <Chevron />
          </span>
        )}
      </button>

      {/* Body — topic table + "Your input". Kept mounted and toggled
          with `hidden` so the header's aria-controls always resolves to
          a real element (a conditionally-rendered panel left it
          dangling while closed). */}
      <div id={panelId} hidden={!isOpen} style={{ borderTop: '1px solid rgb(var(--border-light))' }}>
          {/* Header row */}
          <div
            className="grid"
            style={{
              gridTemplateColumns: '160px 1fr',
              gap: 12,
              padding: '8px 16px',
              background: 'rgb(var(--surface))',
              borderBottom: '1px solid rgb(var(--border-light))',
            }}
          >
            <ColLabel>Topic</ColLabel>
            <ColLabel>Discussion prompt</ColLabel>
          </div>

          {area.topics.map((t, i) => (
            <div
              key={t.topic}
              className="grid"
              style={{
                gridTemplateColumns: '160px 1fr',
                gap: 12,
                padding: '10px 16px',
                background: i % 2 === 0 ? 'rgb(var(--diligence-light))' : 'transparent',
                borderBottom:
                  i === area.topics.length - 1
                    ? 'none'
                    : '1px solid rgb(var(--border-light))',
              }}
            >
              <div
                className="font-sans text-[12.5px] font-semibold"
                style={{
                  color: 'rgb(var(--diligence-text))',
                  lineHeight: 1.4,
                }}
              >
                {t.topic}
              </div>
              <div
                className="font-sans text-[12px]"
                style={{
                  color: 'rgb(var(--ink))',
                  lineHeight: 1.5,
                }}
              >
                {t.prompt}
                {t.note && (
                  <div className="mt-1" style={{ color: 'rgb(var(--secondary))' }}>
                    {t.note}
                  </div>
                )}
              </div>
            </div>
          ))}

          {/* Optional area-level note beneath the topic table */}
          {area.note && (
            <p
              className="m-0 font-sans text-[12px]"
              style={{
                color: 'rgb(var(--secondary))',
                lineHeight: 1.5,
                padding: '10px 16px',
                borderTop: '1px solid rgb(var(--border-light))',
              }}
            >
              {area.note}
            </p>
          )}

          {/* "Your input" preparation prompt — distinct treatment with
              diligence-light bg + purple left accent bar so it reads
              as a writable preparation field. */}
          <YourInputBox text={area.yourInput} />
        </div>
    </article>
  );
}

