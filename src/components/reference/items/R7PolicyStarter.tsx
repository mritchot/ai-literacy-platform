// ─────────────────────────────────────────────────────────────────────
// Top-level component
// ─────────────────────────────────────────────────────────────────────

export function R7PolicyStarter(): JSX.Element {
  // Each area tracks its own collapsed state. All four default to OPEN
  // per spec — collapsing is opt-in.
  const [openMap, setOpenMap] = useState<Record<string, boolean>>(() => {
    const out: Record<string, boolean> = {};
    for (const a of AREAS) out[a.id] = true;
    return out;
  });

  const toggle = (id: string) => {
    setOpenMap((prev) => ({ ...prev, [id]: !prev[id] }));
  };
  // The print route renders every area open, whatever the map says.
  const printMode = usePrintMode();

  return (
    <div className="font-sans">
      {/* Intro */}
      <p
        className="m-0 mb-4 text-body-sm text-body"
        style={{ lineHeight: 1.55 }}
      >
        <strong style={{ color: 'rgb(var(--ink))' }}>
          This is a conversation starter, not a policy.
        </strong>{' '}
        In one study’s general-workforce sample, 69% of professionals mention the social stigma
        that comes with using AI at work, and
        many conceal their use from colleagues. This scaffold
        helps you initiate a conversation about shared AI use norms. You are proposing shared
        standards, not asking for permission. The shape is deliberate. When an MIT committee was
        charged in 2026 with proposing institution-wide AI policy, it rejected a single rule as too
        permissive for some contexts and too restrictive for others. It recommended instead a shared
        framework: a policy menu, disclosure expectations, and accountability standards that each
        department adapts (MIT Ad Hoc Committee, 2026, pp. 1, 7). The four areas below are that framework at team
        scale.
      </p>

      {/* How to use — compact strip */}
      <HowToUse />

      {/* Four discussion areas */}
      <div className="mt-5 space-y-4">
        {AREAS.map((a) => (
          <AreaCard
            key={a.id}
            area={a}
            isOpen={printMode || (openMap[a.id] ?? true)}
            onToggle={() => toggle(a.id)}
          />
        ))}
      </div>

      {/* Starting the conversation — three frames */}
      <ConversationFrames />

      {/* Closing line — italic, low-key */}
      <p
        className="m-0 mt-5 font-sans text-body-sm"
        style={{
          color: 'rgb(var(--ink))',
          lineHeight: 1.55,
        }}
      >
        <strong>The goal is to replace private, uncoordinated AI use with visible, accountable
        team practice</strong>, not to create bureaucracy. Attach a reason to each norm.
        MIT&rsquo;s 2026 AI committee heard that AI rules were confusing and varied widely, and
        that policing unauthorized use harmed instructors&rsquo; relationships with the people they
        teach. It recommends that every AI policy explain why use is required, permitted, or
        restricted (MIT Ad Hoc Committee, 2026, pp. 5, 16–17).
      </p>

      {/* Attribution footer */}
      <p
        className="m-0 mt-6 text-caption text-tertiary"
        style={{ lineHeight: 1.5, fontStyle: 'italic' }}
      >
        Framework: 4D AI Fluency Framework, Diligence competency, Transparency sub-component
        (Dakan &amp; Feller, 2025, p. 6), as taught in Anthropic&rsquo;s AI Fluency course.
        Impact-measurement figure: McKinsey, The state of AI in 2026, p. 19. Some task examples: WEF
        Future of Jobs Report 2025, Box 3.1, pp. 43–44 (an Indeed analysis based on GPT-4o&rsquo;s
        rating of its own abilities).
      </p>
    </div>
  );
}

